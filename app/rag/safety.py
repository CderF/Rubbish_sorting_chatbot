def _match_waste_rule(norm_prompt: str) -> "str | None":
    """ごみ出しルールへの確認質問(時間帯・事業所・申込方式・指定袋・粗大ごみの
    手数料・資源化物の袋)に合致したら、その否定+正しい手順の文案を返す。
    合致しなければ None。"""
    for groups, reply in _WASTE_RULES:
        if all(_contains_any(norm_prompt, group) for group in groups):
            return reply
    return None


